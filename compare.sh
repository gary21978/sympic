#!/bin/bash
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUILD_DIR_ARG="${SYMPIC_BUILD_DIR:-}"
CASES=()

# Input paths are case directories; references are stored in result_gapsio/.
while [[ $# -gt 0 ]]; do
  case "$1" in
    --build-dir)
      BUILD_DIR_ARG="$2"
      shift 2
      ;;
    -h|--help)
      echo "usage: $0 [case ...] [--build-dir DIR]"
      exit 0
      ;;
    *)
      CASES+=("$1")
      shift
      ;;
  esac
done

# Use all maintained single-rank GPU reference cases when no cases are specified.
[[ ${#CASES[@]} -gt 0 ]] || CASES=(case/demo-8 case/demo-64 case/demo-512 case/nh3)

# Select the build directory using the same rules as run.sh.
if [[ -n "$BUILD_DIR_ARG" ]]; then
  if [[ "$BUILD_DIR_ARG" = /* ]]; then
    BUILD="$BUILD_DIR_ARG"
  else
    BUILD="$SCRIPT_DIR/$BUILD_DIR_ARG"
  fi
elif [[ -f "$SCRIPT_DIR/.sympic-last-build" ]]; then
  BUILD="$(head -n1 "$SCRIPT_DIR/.sympic-last-build")"
elif [[ -d "$SCRIPT_DIR/build-nvscale" ]]; then
  BUILD="$SCRIPT_DIR/build-nvscale"
else
  BUILD="$SCRIPT_DIR/build-cuda"
fi

# The comparator is a standalone C process; it needs neither mpirun nor Python.
[[ -x "$BUILD/bin/compare_gapsio" ]] || { echo "[fatal] build compare_gapsio first" >&2; exit 1; }

fail=0
for c in "${CASES[@]}"; do
  # Convert a relative case path to an absolute path.
  if [[ "$c" = /* ]]; then
    CASE="$c"
  else
    CASE="$SCRIPT_DIR/$c"
  fi

  # Re-run the case and generate merged GAPSIO files under build/test.
  bash "$SCRIPT_DIR/run.sh" "$CASE" --build-dir "$BUILD"

  # result_gapsio is the fixed reference generated by a trusted run.
  ref="$CASE/result_gapsio"
  if [[ ! -d "$ref" ]]; then
    echo "[fatal] missing $ref (generate it once from a trusted run)" >&2
    fail=$((fail+1))
    continue
  fi

  # Compare every variable and timestep;
  "$BUILD/bin/compare_gapsio" \
    --test-dir "$BUILD/test" \
    --ref-dir "$ref" || fail=$((fail+1))
done

if [[ $fail -ne 0 ]]; then
  exit 1
fi
echo "=== all pass ==="
